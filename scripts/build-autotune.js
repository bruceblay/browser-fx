const fs = require('fs')
const path = require('path')
const crypto = require('crypto')
const esbuild = require('esbuild')

const root = path.join(__dirname, '..')
const upstream = fs.readFileSync(path.join(root, 'node_modules/signalsmith-stretch/SignalsmithStretch.mjs'), 'utf8')
const hash = crypto.createHash('sha256').update(upstream).digest('hex')
if (hash !== '97530b11d5bc01015af4cde40d6aa55ff10c40aa1294ca4c8c5762027d517a46') {
  throw new Error('Signalsmith source changed. Review its WASM interface before updating the pinned build.')
}
// Retain the official Emscripten factory and embedded binary verbatim. Replace
// only its browser scheduling wrapper so correction runs on the audio thread.
const marker = 'function registerWorkletProcessor(Module, audioNodeKey) {'
const factory = upstream.slice(0, upstream.indexOf(marker)) + '\nexport default SignalsmithStretch;\n'

async function build() {
  await esbuild.build({
    entryPoints: [path.join(root, 'src/audio/autotune-worklet.mjs')],
    outfile: path.join(root, 'autotune-worklet.js'),
    bundle: true, format: 'esm', target: 'chrome116', platform: 'browser',
    banner: { js: '// Generated by scripts/build-autotune.js. Edit src/audio/, not this file.\n// Third-party notices: autotune-licenses.txt' },
    plugins: [{ name: 'signalsmith-factory', setup(build) {
      build.onResolve({ filter: /^signalsmith-stretch-wasm$/ }, () => ({ path: 'factory', namespace: 'signalsmith' }))
      build.onLoad({ filter: /.*/, namespace: 'signalsmith' }, () => ({ contents: factory, loader: 'js' }))
    } }]
  })
  const notices = [
    ['Signalsmith Stretch 1.3.2', 'licenses/signalsmith-stretch.txt'],
    ['Signalsmith Linear (included in Signalsmith WASM)', 'licenses/signalsmith-linear.txt'],
    ['Pitchy 4.1.0', 'node_modules/pitchy/LICENSE'],
    ['fft.js 4.0.4', 'licenses/fft-js.txt']
  ].map(([title, file]) => `${title}\n${fs.readFileSync(path.join(root, file), 'utf8')}`).join('\n\n')
  fs.writeFileSync(path.join(root, 'autotune-licenses.txt'), notices)
}
build().catch(error => { console.error(error); process.exitCode = 1 })
